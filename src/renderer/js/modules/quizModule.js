  bindEvents() {
    const container = document.getElementById('view-quiz');
    if (!container) return;

    container.addEventListener('click', async (e) => {
      // Option button click
      const optBtn = e.target.closest('.quiz-option-btn');
      if (optBtn && !optBtn.disabled) {
        const selectedIndex = parseInt(optBtn.dataset.optIndex, 10);
        this.handleAnswerSelection(selectedIndex);
        return;
      }

      // Next question button click
      if (e.target.closest('#btnNextQuestion')) {
        this.currentQuestionIndex++;
        if (this.currentQuestionIndex >= this.questions.length) {
          this.isFinished = true;
          this.updateSidebarStewardStatus();
        }
        this.render();
        return;
      }

      // Retake quiz button click
      if (e.target.closest('#btnRetakeQuiz')) {
        this.currentQuestionIndex = 0;
        this.score = 0;
        this.userAnswers = [];
        this.isFinished = false;
        this.render();
        return;
      }

      // Download certificate button click
      if (e.target.closest('#btnDownloadCert')) {
        await this.exportCertificate();
        return;
      }
    });
  },

  handleAnswerSelection(selectedIndex) {
    const q = this.questions[this.currentQuestionIndex];
    const isCorrect = selectedIndex === q.correctIndex;
    if (isCorrect) this.score++;

    const optionsContainer = document.getElementById('quizOptionsList');
    if (optionsContainer) {
      const buttons = optionsContainer.querySelectorAll('.quiz-option-btn');
      buttons.forEach((btn, idx) => {
        btn.disabled = true;
        if (idx === q.correctIndex) {
          btn.classList.add('correct');
        } else if (idx === selectedIndex && !isCorrect) {
          btn.classList.add('incorrect');
        }
      });
    }

    const feedbackBox = document.getElementById('quizFeedbackBox');
    const badge = document.getElementById('feedbackBadge');
    const explanation = document.getElementById('feedbackExplanation');

    if (feedbackBox && badge && explanation) {
      badge.textContent = isCorrect ? '✓ CORRECT' : '✗ INCORRECT';
      badge.className = `feedback-badge ${isCorrect ? 'correct' : 'incorrect'}`;
      explanation.textContent = q.explanation;
      feedbackBox.hidden = false;
    }
  },

  updateSidebarStewardStatus() {
    const label = document.getElementById('stewardStatusLabel');
    if (label) {
      const pct = Math.round((this.score / this.questions.length) * 100);
      if (pct >= 80) {
        label.textContent = 'Certified Ocean Steward 🌟';
        label.style.color = 'var(--accent-cyan)';
      }
    }
  },

  async exportCertificate() {
    const canvas = document.getElementById('diplomaCanvas');
    if (!canvas) return;

    const dataUrl = canvas.toDataURL('image/png');
    const base64Data = dataUrl.replace(/^data:image\/png;base64,/, '');

    if (window.oceanAPI && window.oceanAPI.saveFileDialog) {
      try {
        const dialogRes = await window.oceanAPI.saveFileDialog({
          title: 'Save Ocean Steward Diploma',
          defaultPath: 'Ocean-Steward-Certificate.png',
          filters: [{ name: 'PNG Image', extensions: ['png'] }]
        });

        if (!dialogRes.canceled && dialogRes.filePath) {
          const writeRes = await window.oceanAPI.writeFile(dialogRes.filePath, base64Data);
          if (writeRes && writeRes.success) {
            alert('Certificate successfully saved to: ' + dialogRes.filePath);
          }
        }
      } catch (err) {
        console.error('Failed to export certificate:', err);
      }
    } else {
      // Browser fallback download
      const a = document.createElement('a');
      a.href = dataUrl;
      a.download = 'Ocean-Steward-Certificate.png';
      a.click();
    }
  }
